"""Generate the pose editor's natural limits from the pose bank.

For every bone the editor offers outside the Cape and Aim-and-gear groups, the game's own poses
in freecam/assets/steam_subject_poses.lua say how far it turns: a rest rotation (their mean) and,
measured from it with the editor's own swing/twist reading, the range of the twist about the
bone's length and of the two swing parts. Each range is widened by a margin. The maths is the
editor's (pose_editor.lua through lupa), so the table and the limiter cannot disagree.

Requires lupa.lua51 at build/test time only. Writes freecam/assets/pose_limits.lua; --check
rejects drift without writing.
"""
from __future__ import annotations
import argparse
from hashlib import sha256
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BANK = ROOT / 'freecam/assets/steam_subject_poses.lua'
EDITOR = ROOT / 'freecam/pose_editor.lua'
OUTPUT = ROOT / 'freecam/assets/pose_limits.lua'
FREE_GROUPS = ('cape', 'gear')  # the bank barely moves them: limits would freeze them
MARGIN_SHARE, MARGIN_LOW, MARGIN_HIGH = .08, 2.0, 8.0  # of the range; degrees
FREE_SPAN = 300.0  # a range this wide wraps the half turn: no limit can be read from it


def margin(span: float) -> float:
    return min(MARGIN_HIGH, max(MARGIN_LOW, MARGIN_SHARE * span))


def generate() -> str:
    from lupa.lua51 import LuaRuntime
    lua = LuaRuntime()
    load = lua.eval('function(path) return dofile(path) end')
    bank, editor = load(str(BANK)), load(str(EDITOR))
    count = len(bank.catalog)
    poses = [bank.decode(bank.catalog[i].id) for i in range(1, count + 1)]
    lines = []
    for group in editor.GROUPS.values():
        if group.id in FREE_GROUPS:
            continue
        for bone in group.bones.values():
            node = bone.node
            samples = []
            for pose in poses:
                q = list(pose.nodes[node].q.values())
                n = math.sqrt(sum(v * v for v in q))
                samples.append([v / n for v in q])
            rest = samples[0]
            for _ in range(8):  # sign-aligned mean, settled well before eight passes
                total = [0.0] * 4
                for q in samples:
                    sign = 1.0 if sum(a * b for a, b in zip(q, rest)) >= 0 else -1.0
                    total = [t + sign * v for t, v in zip(total, q)]
                n = math.sqrt(sum(v * v for v in total))
                rest = [v / n for v in total]
            rest = [round(v, 7) for v in rest]
            back = lua.table(-rest[0], -rest[1], -rest[2], rest[3])
            parts = [editor.swing_twist(editor.quat_multiply(back, lua.table(*q))) for q in samples]
            ranges = []
            for axis in range(3):
                values = [p[axis] for p in parts]
                low, high = min(values), max(values)
                if high - low >= FREE_SPAN:
                    ranges.append((-180.0, 180.0))
                    continue
                m = margin(high - low)
                ranges.append((max(-180.0, math.floor((low - m) * 100) / 100), min(180.0, math.ceil((high + m) * 100) / 100)))
            (t, y, z) = ranges
            lines.append('[%d]={r={%s},t={%s,%s},y={%s,%s},z={%s,%s}}, -- %s: %s' % (
                node, ','.join(repr(v) for v in rest), *(repr(v) for v in (*t, *y, *z)), group.label, bone.label))
    source = sha256(BANK.read_bytes()).hexdigest()
    return ('-- Generated by tools/build_pose_limits.py; do not edit.\n'
            '-- Source SHA256 ' + source + '\n'
            '-- Natural limits for the pose editor, read from the pose bank\'s ' + str(count) + ' poses. Per bone:\n'
            '-- r is its rest rotation (xyzw, in its parent\'s frame); t, y and z are the ranges in degrees,\n'
            '-- measured from r, of the twist about the bone\'s length and of the two swing parts, each\n'
            '-- widened by ' + ('%g' % (MARGIN_SHARE * 100)) + '% of its width (at least ' + ('%g' % MARGIN_LOW) + ', at most ' + ('%g' % MARGIN_HIGH) + ' degrees). Cape and gear bones have none.\n'
            'return{version=1,poses=' + str(count) + ',nodes={\n' + '\n'.join(lines) + '\n}}\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Reject generated-byte drift without writing')
    args = parser.parse_args()
    text = generate()
    if args.check:
        assert OUTPUT.read_text(encoding='utf-8') == text, 'pose_limits.lua differs from what the pose bank generates'
        print('pose_limits.lua matches the pose bank')
        return
    OUTPUT.write_text(text, encoding='utf-8', newline='\n')
    print('wrote', OUTPUT.relative_to(ROOT), len(text), 'bytes')


if __name__ == '__main__':
    main()
