"""Pack the Proton (LuaJIT under LLL) War Journalist candidate and its assets as one HD2
Arsenal mod: an `-- HD2-Addon:` archive that Live Lua Loader discovers and drives, in place
of the LLL Mods/dbf_freecam folder install. Builds under dist/review only; never registers,
deploys or installs."""
