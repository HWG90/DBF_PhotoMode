def verify(text, head, source_block, library_block, sources, libraries):
    from lupa.luajit21 import LuaRuntime, lua_type
    from lupa.lua51 import LuaRuntime as Lua51
    lua = LuaRuntime()
    assert lua.eval('_VERSION') == 'Lua 5.1' and lua.eval('jit~=nil')
    # LLL on Proton runs LuaJIT; its fallback is PUC 5.1. Both must load the addon.
    for runtime in (lua, Lua51()):
        runtime.eval('function(s,n) return assert(loadstring(s,n)) end')(text, '@' + RESOURCE)
    compile_lua = lua.eval('function(s,n) local f,e=loadstring(s,n);assert(f,e);return f end')
    # Every embedded module and bridge must read back byte for byte.
    got = compile_lua(head + source_block + 'return SOURCES', '=sources')()
    assert sorted(got.keys()) == sorted(sources), 'Module list differs'
    for path, body in sources.items():
        assert got[path] == body, 'Module differs after packing: ' + path
    rows = compile_lua(library_block + 'return LIBRARIES', '=libraries')()
    assert {row['name']: bytes.fromhex(row['hex']) for row in rows.values()} == libraries
    run = 'function(s) return assert(loadstring(s,"@archive"))() end'
    hook = "-- Live Lua Loader runs archive entries itself (LLL API 1).\n"
    assert text.count(hook) == 1
    probe = text.replace(hook, "rawset(_G,'TEST_MOD',mod)\n" + hook)
    with tempfile.TemporaryDirectory() as temp:
        game = Path(temp) / 'Roaming/Arrowhead/Helldivers2'
        lll = Path(temp) / 'Local/LLL/Helldivers2'
        for folder in (game, lll / 'Native', lll / 'Logs', lll / 'Settings' / MOD_ID, lll / 'Mods'):
            folder.mkdir(parents=True)
        previous = {name: os.environ.get(name) for name in ('APPDATA', 'LOCALAPPDATA')}
        os.environ['APPDATA'], os.environ['LOCALAPPDATA'] = str(Path(temp) / 'Roaming'), str(Path(temp) / 'Local')
        log = lambda: (lll / 'Logs' / LOG).read_text() if (lll / 'Logs' / LOG).exists() else ''
        try:
            # Without LLL (Boot Mod Loader) it refuses before touching anything.
            assert LuaRuntime().eval(run)(text) is None
            assert 'Not started: needs Live Lua Loader' in log() and not any((lll / 'Native').iterdir())
            # Beside the LLL folder install it refuses instead of starting a second runtime.
            (lll / 'Mods' / MOD_ID).mkdir()
            (lll / 'Mods' / MOD_ID / 'manifest.json').write_text('{}')
            host = LuaRuntime();host.execute('LiveLuaLoader={}')
            assert host.eval(run)(text) is None and 'also installed in LLL/Helldivers2/Mods/' + MOD_ID in log()
            assert not any((lll / 'Native').iterdir())
            shutil.rmtree(lll / 'Mods' / MOD_ID)
            # LLL: its folders, and the entry handed back for LLL to drive.
            for attempt in range(2):
                host = LuaRuntime();host.execute('LiveLuaLoader={}')
                entry = host.eval(run)(text)
                assert entry['live_lua_api'] == 1 and entry['name'] == 'War Journalist'
                for name in ('on_enable', 'on_update', 'on_disable', 'on_cleanup_poll'):
                    assert lua_type(entry[name]) == 'function', name
                for name, data in libraries.items():
                    assert (lll / 'Native' / name).read_bytes() == data, name
                assert log().count('Installed native bridge ') == len(libraries), 'Bridges install once'
            # Every module loads in the addon's scope and on_enable passes on a bare engine.
            host = LuaRuntime();host.execute(STINGRAY + 'LiveLuaLoader={input_service={},capabilities={}}')
            entry = host.eval(run)(text)
            entry['on_enable']()
            # The userdata bridge resolves into LLL's Native folder, not a mod folder.
            host = LuaRuntime();host.execute('LiveLuaLoader={}')
            host.eval(run)(probe)
            path, address = host.execute("""
local paths={}
package.loaded.hd2_nativeinfo=nil
package.loadlib=function(path)paths[#paths+1]=path;return function()return{userdata_address=function()return 4096 end}end end
local P=TEST_MOD.require('src/cffi.lua')
local address=tonumber(P.ffi.cast('uintptr_t',newproxy()))
return paths[1],address
""")
            assert (path, address) == (str(lll / 'Native/hd2_nativeinfo_f6d3465944c1aea1.dll'), 4096), (path, address)
            assert host.eval('TEST_MOD.config_dir') == str(lll / 'Settings' / MOD_ID)
            name, data = next(iter(libraries.items()))
            (lll / 'Native' / name).write_bytes(data[:-1])
            try:
                host = LuaRuntime();host.execute('LiveLuaLoader={}');host.eval(run)(text)
            except Exception as error:
                assert 'Native bridge differs' in str(error), error
            else:
                raise AssertionError('A differing bridge must be refused')
        finally:
            for name, value in previous.items():
                if value is None:
                    os.environ.pop(name, None)
                else:
                    os.environ[name] = value
    return ['loads under LuaJIT 2.1 and Lua 5.1', 'modules and bridges read back exactly',
            'no LLL: refuses before installing anything', 'refuses beside the LLL folder install',
            'LLL: returns the API 1 entry, installs missing bridges into LLL/Native once',
            'every module loads and on_enable passes on a bare engine',
            'cffi userdata bridge resolves into LLL/Native', 'settings stay in LLL/Settings/' + MOD_ID,
            'refuses a differing bridge']


def build(candidate, output, assets=ASSETS):
    candidate, output = candidate.resolve(), output.resolve()
    assert output.is_relative_to(ROOT / 'dist/review'), 'Archive packages stay in dist/review'
    digest = lambda b: hashlib.sha256(b).hexdigest()
    checks = (candidate / 'FILES-SHA256.txt').read_text().splitlines()
    for line in checks:
        value, name = line.split('  ', 1)
        assert digest((candidate / name).read_bytes()) == value, 'Candidate file changed: ' + name
    manifest, sources, libraries, head, source_block, library_block, text = bundle(candidate)
    verified = verify(text, head, source_block, library_block, sources, libraries)
    data = text.encode('utf-8')
    key = hash64(RESOURCE)
    assert re.match(r'-- HD2-Addon: (mods/[A-Za-z0-9_/]+)\n', text).group(1) == RESOURCE
    envelope = struct.pack('<II', len(data), 2) + data
    body, gpu = archive_rows([(key, LUA, envelope, b'')])
    assert read_archive(body, gpu) == [(key, LUA, envelope, b'')] and gpu == b''
    version = manifest['version']
    folder = output / ('War-Journalist-Proton-' + version.removesuffix('-proton'))
    if folder.exists():
        shutil.rmtree(folder)
    payload = folder / OPTION
    payload.mkdir(parents=True)
    (payload / ARCHIVE).write_bytes(body)
    for suffix in ('.stream', '.gpu_resources'):
        (payload / (ARCHIVE + suffix)).write_bytes(b'')
    (payload / f'{key:016x}.lua').write_bytes(data)
    for name in manifest['license_files']:
        shutil.copyfile(candidate / name, folder / name)
    shutil.copytree(assets, folder / 'Assets')
    description = ('War Journalist Photo Mode for the LuaJIT boot (Live Lua Loader on Proton) with its assets, as one '
                   'archive mod. Same build as the LLL folder install: FFI enemy behavior, settings in MCM, Handycam aim '
                   'lock and the native bridges, which install into LLL\'s Native folder on first load. Replaces LLL '
                   'Mods/' + MOD_ID + ' and the separate War Journalist 1.2.0 Assets entry; it will not start while '
                   'that folder exists. Settings stay in LLL/Helldivers2/Settings/' + MOD_ID + '.')
    arsenal = {'Version': 1, 'Guid': GUID, 'Name': TITLE + ' ' + version.removesuffix('-proton'), 'Description': description,
               'Options': [{'Name': TITLE, 'Description': 'Photo Mode and its assets.', 'Include': [OPTION, 'Assets']}]}
    (folder / 'manifest.json').write_text(json.dumps(arsenal, indent=2, ensure_ascii=False) + '\n')
    provenance = {'version': version, 'runtime': 'LuaJIT 2.1 under LLL (Proton)', 'ffi': 'optional; enemy behavior only',
                  'resource': RESOURCE, 'resource_key': f'{key:016x}', 'addon_sha256': digest(data), 'archive_sha256': digest(body),
                  'candidate': str(candidate), 'candidate_files_sha256': digest((candidate / 'FILES-SHA256.txt').read_bytes()),
                  'modules': len(sources) - 1, 'native_bridges': {name: digest(b) for name, b in libraries.items()},
                  'assets_source': str(assets),
                  'assets': {p.relative_to(folder / 'Assets').as_posix(): digest(p.read_bytes()) for p in sorted((folder / 'Assets').iterdir())},
                  'verified': verified, 'registered': False, 'deployed': False, 'live_acceptance': 'pending'}
    (folder / 'PROVENANCE.json').write_text(json.dumps(provenance, indent=2) + '\n')
    files = sorted(p for p in folder.rglob('*') if p.is_file())
    (folder / 'FILES-SHA256.txt').write_text(''.join(digest(p.read_bytes()) + '  ' + p.relative_to(folder).as_posix() + '\n' for p in files))
    return folder, provenance


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    default = ROOT / 'dist/review/proton/package'
    parser.add_argument('--candidate', type=Path, default=default / 'candidate' / MOD_ID)
    parser.add_argument('--output', type=Path, default=ROOT / 'dist/review/proton/arsenal')
    parser.add_argument('--assets', type=Path, default=ASSETS)
    args = parser.parse_args()
    folder, provenance = build(args.candidate, args.output, args.assets)
    print(json.dumps({'folder': str(folder), **{k: provenance[k] for k in ('resource', 'resource_key', 'addon_sha256', 'modules')}}, indent=2))
